export function getBookById(id) {
  return books.find(b => b.id === id) || null
}

export function getRelatedBooks(book, limit = 5) {
  return books
    .filter(b => b.id !== book.id && (
      b.category === book.category ||
      b.genre === book.genre ||
      b.authorId === book.authorId
    ))
    .slice(0, limit)
}
