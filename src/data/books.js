// Escape characters that are invalid inside SVG/XML text nodes.
// &  →  &amp;   (must come first to avoid double-escaping)
// <  →  &lt;
// >  →  &gt;
// '  →  &apos;
// "  →  &quot;
function xmlEsc(str) {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;')
}

function cover(idx, title, author) {
  const bg   = COVER_COLORS[idx % COVER_COLORS.length]
  const lines = title.split(' ')
  const l1   = xmlEsc(lines.slice(0, Math.ceil(lines.length / 2)).join(' '))
  const l2   = xmlEsc(lines.slice(Math.ceil(lines.length / 2)).join(' '))
  const auth = xmlEsc(author)
  const svg  = `<svg xmlns="http://www.w3.org/2000/svg" width="120" height="180" viewBox="0 0 120 180">
    <rect width="120" height="180" fill="${bg}"/>
    <rect x="8" y="8" width="104" height="164" fill="none" stroke="rgba(255,255,255,0.15)" stroke-width="1"/>
    <text x="60" y="72" font-family="Georgia,serif" font-size="12" font-weight="bold" fill="white" text-anchor="middle" dominant-baseline="middle">${l1}</text>
    <text x="60" y="90" font-family="Georgia,serif" font-size="12" font-weight="bold" fill="white" text-anchor="middle" dominant-baseline="middle">${l2}</text>
    <line x1="20" y1="112" x2="100" y2="112" stroke="rgba(255,255,255,0.35)" stroke-width="1"/>
    <text x="60" y="130" font-family="Arial,sans-serif" font-size="8" fill="rgba(255,255,255,0.7)" text-anchor="middle">${auth}</text>
  </svg>`
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`
}

